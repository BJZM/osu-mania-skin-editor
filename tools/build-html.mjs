import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const toolsDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(toolsDir, '..');
const htmlRoot = path.join(root, 'src', 'html');
const templatePath = path.join(htmlRoot, 'index.template.html');
const outputPath = path.join(root, 'index.html');
const includePattern = /^([ \t]*)<!--\s*@include\s+([^\s]+)\s*-->[ \t]*$/gm;
const generatedHeader = '<!-- Generated by tools/build-html.mjs. Edit src/html/index.template.html and src/html/partials/*.html instead. -->\n';
const checkOnly = process.argv.includes('--check');

function readUtf8(filePath) {
  return readFileSync(filePath, 'utf8').replace(/\r\n?/g, '\n');
}

function ensureInsideHtmlRoot(filePath) {
  const relative = path.relative(htmlRoot, filePath);
  if (relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new Error(`Include path escapes src/html: ${filePath}`);
  }
}

function getCommonIndent(content) {
  const indents = content
    .split('\n')
    .filter((line) => line.trim() !== '')
    .map((line) => line.match(/^[ \t]*/)[0]);

  if (indents.length === 0) return '';
  return indents.reduce((common, indent) => {
    let index = 0;
    while (index < common.length && index < indent.length && common[index] === indent[index]) index++;
    return common.slice(0, index);
  }, indents[0]);
}

function reindent(content, indent) {
  const commonIndent = getCommonIndent(content);
  return content
    .replace(/\n$/, '')
    .split('\n')
    .map((line) => {
      if (line.trim() === '') return '';
      const normalized = line.startsWith(commonIndent) ? line.slice(commonIndent.length) : line;
      return `${indent}${normalized}`;
    })
    .join('\n');
}

function expandIncludes(content, currentFile, stack = []) {
  return content.replace(includePattern, (match, indent, includePath) => {
    const resolvedPath = path.resolve(path.dirname(currentFile), includePath);
    ensureInsideHtmlRoot(resolvedPath);

    if (stack.includes(resolvedPath)) {
      const chain = [...stack, resolvedPath].map((file) => path.relative(root, file)).join(' -> ');
      throw new Error(`Circular HTML include detected: ${chain}`);
    }

    let partial;
    try {
      partial = readUtf8(resolvedPath);
    } catch (error) {
      throw new Error(`Unable to read include "${includePath}" from ${path.relative(root, currentFile)}: ${error.message}`);
    }

    const expanded = expandIncludes(partial, resolvedPath, [...stack, resolvedPath]);
    return reindent(expanded, indent);
  });
}

function findDuplicateIds(html) {
  const ids = new Map();
  const idPattern = /\bid="([^"]+)"/g;
  let match;

  while ((match = idPattern.exec(html)) !== null) {
    const id = match[1];
    const line = html.slice(0, match.index).split('\n').length;
    const locations = ids.get(id) ?? [];
    locations.push(line);
    ids.set(id, locations);
  }

  return [...ids.entries()]
    .filter(([, locations]) => locations.length > 1)
    .map(([id, locations]) => `${id} (lines ${locations.join(', ')})`);
}

let template;
try {
  template = readUtf8(templatePath);
} catch (error) {
  console.error(`Unable to read HTML template: ${error.message}`);
  process.exit(1);
}

let output;
try {
  output = expandIncludes(template, templatePath).replace(/^(<!DOCTYPE html>\n)/, `$1${generatedHeader}`);
} catch (error) {
  console.error(error.message);
  process.exit(1);
}

const duplicateIds = findDuplicateIds(output);
if (duplicateIds.length > 0) {
  console.error(`Duplicate HTML ids found:\n${duplicateIds.map((entry) => `  - ${entry}`).join('\n')}`);
  process.exit(1);
}

if (checkOnly) {
  let existing = '';
  try {
    existing = readUtf8(outputPath);
  } catch {
    console.error('index.html is missing. Run "npm run build:html".');
    process.exit(1);
  }

  if (existing !== output) {
    console.error('index.html is out of sync with src/html. Run "npm run build:html".');
    process.exit(1);
  }

  console.log('HTML modules and generated index.html are in sync.');
  process.exit(0);
}

writeFileSync(outputPath, output, 'utf8');
console.log(`Built ${path.relative(root, outputPath)} from src/html modules.`);
